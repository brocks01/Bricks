import { Ionicons } from '@expo/vector-icons';
import { useEffect, useRef, useState } from 'react';
import { Pressable, ScrollView, Text, TextInput, View } from 'react-native';
import { askAgent } from '../agent/live';
import { answerSurface, CLOSED_BELOW, FULL_AT, hideSurface, minimiseSurface, MIN_RATIO, setPanelRatio, setPanelState, surfaceStore, type PanelState, type Surface } from '../agent/surface';
import { useStore } from '../core/store';
import { useT } from '../i18n';
import { useCurrentPage } from '../navigation';
import { colors, radius, space, type } from '../theme/tokens';
import { DragHandle } from './DragHandle';
import { HtmlFrame } from './HtmlFrame';
import { Button, type IconName } from './ui';

/** The icon a tile asked for, or a neutral one when it is not a real Ionicons name (surface.ts already checks the shape). */
const iconFor = (name: string): IconName => (name && name in (Ionicons.glyphMap as Record<string, unknown>) ? (name as IconName) : 'apps');

/**
 * The agent's CANVAS: a card in the app's content area where the agent shows a question, an explanation, or a small screen it
 * wrote for this person, in their language. The tab bar and the Bricks Agent bar stay visible below it and are never covered.
 * Mounted once in the root layout. The person can always close it; closing never submits anything.
 *
 * The panel FLOATS over the content area (the owner's choice, 13 Nov 2026): it has no backdrop colour and it is
 * sized to its own content, so the screen behind stays visible around and below it instead of being buried.
 * Layout: ONE thin header row - the "Generated by Bricks Agent (AI)" pill (which is never allowed to cut off, since
 * it is the label that says a machine wrote this) with info, regenerate and close - then the body (title, subtitle,
 * question, tiles, options, typed answer, hint, steps, html), then a footer with step dots and Next.
 * All words come from i18n/common.ts under agent.canvas.
 */
export function AgentSurface() {
  const { open, surface, seq, ratio: rest } = useStore(surfaceStore);
  const page = useCurrentPage();
  const t = useT();
  const [area, setArea] = useState(0); // height of the area the sheet lives in, from onLayout
  const [dragging, setDragging] = useState<number | null>(null); // where the finger has it right now
  const from = useRef<number | null>(null); // which height the drag started at
  // Moving to another screen closes it. A question asked for the old screen is answered as "closed", so the agent is never left waiting.
  useEffect(() => {
    hideSurface();
  }, [page?.key]);
  if (!open || !surface) return null;
  const live = dragging ?? rest;
  const state: PanelState = live >= FULL_AT ? 'full' : 'expanded';

  // The sheet tracks the hand the whole way, and on release it STAYS where the hand left it - the way the
  // Instagram comment sheet does. It only comes back to the resting size when the agent shows something new.
  const onMove = (dy: number) => {
    if (!dy) {
      from.current = null;
      setDragging(null);
      return;
    }
    if (area < 40) return;
    if (from.current === null) from.current = rest;
    setDragging(Math.min(1, Math.max(MIN_RATIO, from.current - dy / area)));
  };
  const onRelease = (dy: number) => {
    const landed = dragging ?? rest;
    from.current = null;
    setDragging(null);
    if (Math.abs(dy) < 8) return; // a tap, not a drag
    if (landed <= CLOSED_BELOW) {
      minimiseSurface(); // pulled all the way down: put it away, but keep it
      return;
    }
    setPanelRatio(landed); // any other height is the person's choice, and it is remembered
  };

  const height = `${Math.round(live * 100)}%`;
  return (
    <View
      accessibilityViewIsModal
      onLayout={(e) => setArea(e.nativeEvent.layout.height)}
      style={{ position: 'absolute', top: 0, left: 0, right: 0, bottom: 0, justifyContent: 'flex-end' }}
    >
      {/* The app stays visible above the sheet until it is dragged to full screen. Tapping the dimmed part
          puts it away (never submits anything); the drag handle and the Close button do the same, deliberately. */}
      {state === 'full' ? null : (
        <Pressable onPress={hideSurface} accessibilityRole="button" accessibilityLabel={t('common.agent.close')} style={{ position: 'absolute', top: 0, left: 0, right: 0, bottom: 0, backgroundColor: 'rgba(15,20,18,0.30)' }} />
      )}
      <View style={{ height, maxHeight: '100%' }}>
        {/* Keyed on seq: every screen the agent shows starts with nothing typed, nothing picked and the about line closed. */}
        <Canvas key={seq} surface={surface} state={state} onMove={onMove} onRelease={onRelease} />
      </View>
    </View>
  );
}

function Canvas({ surface, state, onMove, onRelease }: { surface: Surface; state: PanelState; onMove: (dy: number) => void; onRelease: (dy: number) => void }) {
  const t = useT();
  const [typed, setTyped] = useState('');
  const [about, setAbout] = useState(false);
  const [picked, setPicked] = useState<string[]>([]);

  const toggle = (id: string) => setPicked((p) => (p.includes(id) ? p.filter((x) => x !== id) : [...p, id]));
  const chosen = surface.tiles.filter((x) => picked.includes(x.id)).map((x) => x.label);
  const showNext = surface.next || surface.tiles.length > 0;
  const showDots = surface.stepTotal > 0;
  const submit = () => {
    if (chosen.length) answerSurface(chosen.join(', '), 'option');
    else if (typed.trim()) answerSurface(typed.trim(), 'typed');
    else answerSurface('next', 'option');
  };

  return (
    <View style={{ flex: 1, backgroundColor: colors.card, borderRadius: radius.card, borderWidth: 1, borderColor: colors.accentLine, overflow: 'hidden' }}>
      <View style={{ backgroundColor: colors.accentSoft }}>
        {/* Grab anywhere in this header - the bar or the row beside it - and the sheet follows your hand;
            let go and it stays at exactly the height you left it. */}
        <DragHandle
          label={t(state === 'full' ? 'agent.canvas.shrink' : 'agent.canvas.grow')}
          onMove={onMove}
          onRelease={onRelease}
          style={{ paddingTop: space.xs, paddingBottom: space.sm }}
        >
          {/* header: ONE compact row. The AI label keeps its full width and is never allowed to cut off - it is the
              line that says a machine wrote this - then the small controls. The title is the first line of the body. */}
          <View style={{ flexDirection: 'row', alignItems: 'center', gap: space.sm, paddingHorizontal: space.lg }}>
            <View style={{ flexDirection: 'row', alignItems: 'center', gap: 6, backgroundColor: colors.card, borderRadius: radius.pill, paddingHorizontal: space.sm, paddingVertical: 5 }}>
              <Ionicons name="sparkles" size={14} color={colors.accent} />
              <Text style={{ fontSize: 12, fontWeight: '700', color: colors.ink }} numberOfLines={1}>
                {t('common.agent.canvas.badge')}
              </Text>
            </View>
            <View style={{ flex: 1, minWidth: 4 }} />
            <Pressable onPress={() => setAbout((v) => !v)} accessibilityRole="button" accessibilityLabel={t('common.agent.canvas.info')} accessibilityState={{ expanded: about }} hitSlop={10}>
              <Ionicons name="information-circle-outline" size={22} color={colors.accent} />
            </Pressable>
            <Pressable
              onPress={() => setPanelState(state === 'full' ? 'expanded' : 'full')}
              accessibilityRole="button"
              accessibilityLabel={t(state === 'full' ? 'agent.canvas.shrink' : 'agent.canvas.grow')}
              accessibilityState={{ expanded: state === 'full' }}
              hitSlop={10}
            >
              <Ionicons name={state === 'full' ? 'contract' : 'expand'} size={20} color={colors.ink} />
            </Pressable>
          <Pressable onPress={() => void askAgent('Show that screen again, with improvements.')} accessibilityRole="button" accessibilityLabel={t('common.agent.canvas.again')} hitSlop={10}>
            <Ionicons name="refresh" size={21} color={colors.ink} />
          </Pressable>
          <Pressable onPress={hideSurface} accessibilityRole="button" accessibilityLabel={t('common.agent.close')} hitSlop={10}>
            <Ionicons name="close" size={24} color={colors.ink} />
          </Pressable>
          </View>
        </DragHandle>
        {about ? (
          <Text accessibilityLiveRegion="polite" style={{ fontSize: 13, lineHeight: 18, color: colors.muted, paddingHorizontal: space.lg, paddingBottom: space.sm }}>
            {t('common.agent.canvas.about')}
          </Text>
        ) : null}
      </View>

      <ScrollView
        style={{ flex: 1, backgroundColor: colors.card }}
        showsVerticalScrollIndicator={false}
        keyboardShouldPersistTaps="handled"
        contentContainerStyle={{ padding: space.lg, gap: space.md }}
      >
        {surface.title ? (
          <Text style={[type.h1, { color: colors.ink, marginTop: 0 }]} accessibilityRole="header">
            {surface.title}
          </Text>
        ) : null}

        {surface.message ? (
          <Text style={[type.body, { color: colors.muted, marginTop: 0 }]}>{surface.message}</Text>
        ) : null}

        {surface.question ? (
          <Text style={[type.h2, { color: colors.ink }]} accessibilityRole="header">
            {surface.question}
          </Text>
        ) : null}

        {surface.tiles.length ? (
          <View style={{ flexDirection: 'row', flexWrap: 'wrap', gap: space.sm }}>
            {surface.tiles.map((tile) => {
              const on = picked.includes(tile.id);
              return (
                <Pressable
                  key={tile.id}
                  onPress={() => toggle(tile.id)}
                  accessibilityRole="checkbox"
                  accessibilityLabel={tile.label}
                  accessibilityState={{ checked: on }}
                  style={{
                    flexBasis: '22%',
                    flexGrow: 1,
                    minHeight: 92,
                    borderRadius: radius.card,
                    borderWidth: on ? 2 : 1,
                    borderColor: on ? colors.accent : colors.line,
                    backgroundColor: on ? colors.accentSoft : colors.card,
                    alignItems: 'center',
                    justifyContent: 'center',
                    gap: 6,
                    paddingVertical: space.md,
                    paddingHorizontal: 6,
                  }}
                >
                  <Ionicons name={iconFor(tile.icon)} size={26} color={on ? colors.accent : colors.ink} />
                  <Text style={{ fontSize: 14, fontWeight: '600', color: colors.ink, textAlign: 'center' }}>{tile.label}</Text>
                </Pressable>
              );
            })}
          </View>
        ) : null}

        {surface.options.map((o) => (
          <Button key={o} kind="plain" label={o} onPress={() => answerSurface(o, 'option')} />
        ))}

        {surface.allowText ? (
          <View style={{ flexDirection: 'row', gap: 8, alignItems: 'center' }}>
            <TextInput
              value={typed}
              onChangeText={setTyped}
              onSubmitEditing={() => typed.trim() && answerSurface(typed.trim(), 'typed')}
              placeholder={t('common.agent.type')}
              placeholderTextColor={colors.muted}
              accessibilityLabel={t('common.agent.type')}
              style={{ flex: 1, fontSize: 17, color: colors.ink, backgroundColor: colors.bg, borderRadius: radius.pill, paddingHorizontal: 16, paddingVertical: 10, borderWidth: 1, borderColor: colors.line }}
            />
            <Pressable
              onPress={() => typed.trim() && answerSurface(typed.trim(), 'typed')}
              accessibilityRole="button"
              accessibilityLabel="Send"
              style={{ width: 44, height: 44, borderRadius: 22, backgroundColor: colors.accent, alignItems: 'center', justifyContent: 'center' }}
            >
              <Ionicons name="arrow-forward" size={22} color="#FFFFFF" />
            </Pressable>
          </View>
        ) : null}

        {surface.hint ? (
          <View style={{ flexDirection: 'row', gap: space.md, backgroundColor: colors.accentSoft, borderRadius: radius.card, borderWidth: 1, borderColor: colors.accentLine, padding: space.md, alignItems: 'flex-start' }}>
            <Ionicons name="clipboard-outline" size={26} color={colors.accent} style={{ marginTop: 2 }} />
            <Text style={[type.body, { color: colors.ink, flex: 1 }]}>{surface.hint}</Text>
          </View>
        ) : null}

        {surface.steps.map((s, i) => (
          <View key={i} style={{ flexDirection: 'row', gap: 12, alignItems: 'flex-start' }}>
            <View style={{ width: 30, height: 30, borderRadius: 15, backgroundColor: colors.accent, alignItems: 'center', justifyContent: 'center' }}>
              <Text style={{ color: '#FFFFFF', fontWeight: '700', fontSize: 16 }}>{i + 1}</Text>
            </View>
            <Text style={[type.body, { color: colors.ink, flex: 1 }]}>{s}</Text>
          </View>
        ))}

        {surface.html ? <HtmlFrame html={surface.html} /> : null}
      </ScrollView>

      {showDots || showNext ? (
        <View style={{ flexDirection: 'row', alignItems: 'center', paddingHorizontal: space.lg, paddingVertical: space.md, gap: space.md, borderTopWidth: 1, borderColor: colors.line }}>
          {showDots ? (
            <View style={{ flex: 1, flexDirection: 'row', gap: 7, justifyContent: 'center', alignItems: 'center' }} accessibilityRole="progressbar" accessibilityValue={{ min: 0, max: surface.stepTotal, now: surface.step }}>
              {Array.from({ length: surface.stepTotal }, (_, i) => (
                <View key={i} style={{ width: 9, height: 9, borderRadius: 5, backgroundColor: i + 1 === surface.step ? colors.accent : colors.line }} />
              ))}
            </View>
          ) : (
            <View style={{ flex: 1 }} />
          )}
          {showNext ? <Button label={t('common.agent.canvas.next')} icon="arrow-forward" onPress={submit} disabled={surface.tiles.length > 0 && chosen.length === 0} /> : null}
        </View>
      ) : null}
    </View>
  );
}
